#!/usr/bin/env python3
"""Generate analyzer/parsetreewalker.go from analyzer/parseTreeWalker.ts.

The TypeScript file is two large switches over all 78 parse node types --
getChildNodes and ParseTreeVisitor.visit -- plus one do-nothing visit method per
node type. Transcribing that by hand is exactly the kind of work where a single
dropped case survives review, so it is generated instead.

Usage: python3 analyzer/gen/generate_parsetreewalker.py <ref>/analyzer/parseTreeWalker.ts
"""

import re
import sys
import pathlib

src = pathlib.Path(sys.argv[1]).read_text()


def upper1(s):
    return s[0].upper() + s[1:]


def normalize(expr):
    # `...(node.d.x ?? [])` is just `...node.d.x`: ranging a nil slice in Go is
    # a no-op, the same as spreading an empty array.
    expr = re.sub(r"\.\.\.\(\s*(node\.d\.\w+)\s*\?\?\s*\[\]\s*\)", r"...\1", expr)
    return " ".join(expr.split())


def conv_expr(expr, nodevar):
    expr = normalize(expr)
    if expr.startswith("[") and expr.endswith("]"):
        inner = expr[1:-1].strip()
        parts = [p.strip() for p in inner.split(",")] if inner else []
        pieces = []
        for p in parts:
            if not p:
                continue
            if p.startswith("..."):
                pieces.append(("spread", upper1(p[3:].replace("node.d.", ""))))
            else:
                pieces.append(("one", upper1(p.replace("node.d.", ""))))
        if not pieces:
            return "return nil"
        if all(k == "one" for k, _ in pieces):
            items = ", ".join(f"childOrNil({nodevar}.D.{f})" for _, f in pieces)
            return f"return []parser.ParseNode{{{items}}}"
        lines = ["out := []parser.ParseNode{}"]
        for k, f in pieces:
            if k == "one":
                lines.append(f"out = append(out, childOrNil({nodevar}.D.{f}))")
            else:
                lines.append(f"for _, c := range {nodevar}.D.{f} {{")
                lines.append("\tout = append(out, c)")
                lines.append("}")
        lines.append("return out")
        return "\n\t\t".join(lines)

    f = upper1(normalize(expr).replace("node.d.", ""))
    return (
        f"out := make([]parser.ParseNode, 0, len({nodevar}.D.{f}))\n\t\t"
        f"for _, c := range {nodevar}.D.{f} {{\n\t\t\tout = append(out, c)\n\t\t}}\n\t\treturn out"
    )


body = src[src.index("export function getChildNodes"):]
body = body[: body.index("\n}\n")]
cases = re.findall(r"case ParseNodeType\.(\w+):\s*\n\s*return ([^;]+);", body, re.S)
