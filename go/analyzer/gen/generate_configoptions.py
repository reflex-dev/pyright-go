#!/usr/bin/env python3
"""Generate analyzer/configoptions_gen.go from common/configOptions.ts and
common/diagnosticRules.ts.

DiagnosticRuleSet has 96 fields and there are four preset rule sets, so the
constants alone are nearly 400 hand-transcribed values -- the kind of table
where a single mistyped 'warning' produces a diagnostic-count difference far
downstream and no way to trace it back. It is generated instead.

commentUtils.ts also reaches into a rule set by name (`(ruleSet as any)[rule]`),
which Go cannot do without reflection. The generator emits a name -> field
accessor map for exactly the fields whose names appear in the DiagnosticRule
enum, so a rule that exists in one place and not the other is a build error
rather than a silent no-op.

Usage:
  python3 analyzer/gen/generate_configoptions.py <ref>/common
"""

import pathlib
import re
import sys

ref = pathlib.Path(sys.argv[1])
config_src = (ref / "configOptions.ts").read_text()
rules_src = (ref / "diagnosticRules.ts").read_text()

out_path = pathlib.Path(__file__).resolve().parent.parent / "configoptions_gen.go"


def upper1(s):
    return s[0].upper() + s[1:]


def go_ident(rule_name):
    """Go constant name for a DiagnosticRule member."""
    return "DiagnosticRule" + upper1(rule_name)


# ---------------------------------------------------------------- enum members

enum_body = re.search(r"export enum DiagnosticRule \{(.*?)\n\}", rules_src, re.S).group(1)
rule_names = re.findall(r"^\s*(\w+) = '(\w+)',", enum_body, re.M)
for name, value in rule_names:
    assert name == value, f"DiagnosticRule.{name} has a value that is not its name"
rule_names = [name for name, _ in rule_names]
rule_set = set(rule_names)

# ------------------------------------------------------------- the rule set

interface_body = re.search(r"export interface DiagnosticRuleSet \{(.*?)\n\}", config_src, re.S).group(1)

fields = []  # (ts_name, go_name, go_type, [comment lines])
comment = []
for line in interface_body.splitlines():
    stripped = line.strip()
    if stripped.startswith("//"):
        comment.append(stripped[2:].strip())
        continue
    m = re.match(r"(\w+): (boolean|DiagnosticLevel);$", stripped)
    if m:
        ts_name, ts_type = m.group(1), m.group(2)
        go_type = "bool" if ts_type == "boolean" else "DiagnosticLevel"
        fields.append((ts_name, upper1(ts_name), go_type, comment))
    comment = []

assert len(fields) >= 90, f"only found {len(fields)} DiagnosticRuleSet fields"

# ---------------------------------------------------------------- rule lists


def rule_list(fn_name, body_start=None):
    """Extract the DiagnosticRule.x members listed in a function body."""
    m = re.search(r"export function %s\(.*?\) \{(.*?)\n\}" % fn_name, config_src, re.S)
    return re.findall(r"DiagnosticRule\.(\w+)", m.group(1))


bool_rules_body = re.search(
    r"export function getBooleanDiagnosticRules\(.*?\) \{(.*?)\n\}", config_src, re.S
).group(1)
# The function returns a base list and pushes two more under a flag.
base_bool_rules = re.findall(r"DiagnosticRule\.(\w+),", bool_rules_body)
extra_bool_rules = re.findall(r"boolRules\.push\(DiagnosticRule\.(\w+)\)", bool_rules_body)

diag_level_rules = rule_list("getDiagLevelDiagnosticRules")
not_overridden_rules = rule_list("getStrictModeNotOverriddenRules")

# --------------------------------------------------------------- preset sets

presets = []  # (ts_fn, go_fn, {field: literal})
for ts_fn, go_fn in [
    ("getOffDiagnosticRuleSet", "GetOffDiagnosticRuleSet"),
    ("getBasicDiagnosticRuleSet", "GetBasicDiagnosticRuleSet"),
    ("getStandardDiagnosticRuleSet", "GetStandardDiagnosticRuleSet"),
    ("getStrictDiagnosticRuleSet", "GetStrictDiagnosticRuleSet"),
]:
    m = re.search(
        r"export function %s\(\): DiagnosticRuleSet \{\s*const diagSettings: DiagnosticRuleSet = \{(.*?)\n    \};"
        % ts_fn,
        config_src,
        re.S,
    )
    assert m, f"could not find {ts_fn}"
    values = {}
    # Some entries carry a trailing "// Not overridden by strict mode" comment.
    for name, value in re.findall(r"^\s*(\w+): (true|false|'\w+'),(?: *//.*)?$", m.group(1), re.M):
        values[name] = value
    missing = {f[0] for f in fields} - set(values)
    assert not missing, f"{ts_fn} is missing {sorted(missing)}"
    presets.append((ts_fn, go_fn, values))

# ----------------------------------------------------------------- emit Go

o = []
w = o.append

w('/*')
w(' * configoptions_gen.go')
w(' *')
w(' * GENERATED by analyzer/gen/generate_configoptions.py from')
w(' * common/configOptions.ts and common/diagnosticRules.ts. Do not edit.')
w(' *')
w(' * Run `make generate` to regenerate.')
w(' */')
w('')
w('package analyzer')
w('')
w('// DiagnosticRule corresponds to the enum of the same name in')
w('// common/diagnosticRules.ts. Every member\'s value equals its name, so the')
w('// string is both the config key and the rule identity.')
w('type DiagnosticRule = string')
w('')
w('const (')
for name in rule_names:
    w('\t%s DiagnosticRule = "%s"' % (go_ident(name), name))
w(')')
w('')
w('// DiagnosticRuleSet corresponds to the interface of the same name.')
w('type DiagnosticRuleSet struct {')
for i, (ts_name, go_name, go_type, comment) in enumerate(fields):
    if i:
        w('')
    for line in comment:
        w('\t// %s' % line if line else '\t//')
    w('\t%s %s' % (go_name, go_type))
w('}')
w('')
w('// CloneDiagnosticRuleSet corresponds to cloneDiagnosticRuleSet. The original')
w('// makes a shallow copy with Object.assign; every field is a scalar, so a Go')
w('// struct copy is the same thing.')
w('func CloneDiagnosticRuleSet(diagSettings *DiagnosticRuleSet) *DiagnosticRuleSet {')
w('\tclone := *diagSettings')
w('\treturn &clone')
w('}')
w('')
w('// diagnosticRuleBoolFields maps a rule name to the bool field it names.')
w('// It stands in for the original\'s `(ruleSet as any)[ruleName]`.')
w('var diagnosticRuleBoolFields = map[DiagnosticRule]func(*DiagnosticRuleSet) *bool{')
for ts_name, go_name, go_type, _ in fields:
    if go_type == "bool" and ts_name in rule_set:
        w('\t%s: func(rs *DiagnosticRuleSet) *bool { return &rs.%s },' % (go_ident(ts_name), go_name))
w('}')
w('')
w('// diagnosticRuleLevelFields maps a rule name to the DiagnosticLevel field it')
w('// names. It stands in for the original\'s `(ruleSet as any)[ruleName]`.')
w('var diagnosticRuleLevelFields = map[DiagnosticRule]func(*DiagnosticRuleSet) *DiagnosticLevel{')
for ts_name, go_name, go_type, _ in fields:
    if go_type == "DiagnosticLevel" and ts_name in rule_set:
        w('\t%s: func(rs *DiagnosticRuleSet) *DiagnosticLevel { return &rs.%s },' % (go_ident(ts_name), go_name))
w('}')
w('')
w('// GetBooleanDiagnosticRules returns a list of the diagnostic rules that are')
w('// configured with a true or false value. The TypeScript defaults')
w('// includeNonOverridable to false.')
w('func GetBooleanDiagnosticRules(includeNonOverridable bool) []DiagnosticRule {')
w('\tboolRules := []DiagnosticRule{')
for name in base_bool_rules:
    w('\t\t%s,' % go_ident(name))
w('\t}')
w('')
w('\tif includeNonOverridable {')
w('\t\t// Do not include these because we don\'t want to override it in strict')
w('\t\t// mode or support it within pyright comments.')
for name in extra_bool_rules:
    w('\t\tboolRules = append(boolRules, %s)' % go_ident(name))
w('\t}')
w('')
w('\treturn boolRules')
w('}')
w('')
w('// GetDiagLevelDiagnosticRules returns a list of the diagnostic rules that are')
w("// configured with a diagnostic level ('none', 'error', etc.).")
w('func GetDiagLevelDiagnosticRules() []DiagnosticRule {')
w('\treturn []DiagnosticRule{')
for name in diag_level_rules:
    w('\t\t%s,' % go_ident(name))
w('\t}')
w('}')
w('')
w('// GetStrictModeNotOverriddenRules corresponds to')
w('// getStrictModeNotOverriddenRules. In strict mode, the value in the user')
w('// config file should be honored and not overwritten by the value from the')
w('// strict rule set.')
w('func GetStrictModeNotOverriddenRules() []DiagnosticRule {')
w('\treturn []DiagnosticRule{')
for name in not_overridden_rules:
    w('\t\t%s,' % go_ident(name))
w('\t}')
w('}')

for ts_fn, go_fn, values in presets:
    w('')
    w('// %s corresponds to %s.' % (go_fn, ts_fn))
    w('func %s() *DiagnosticRuleSet {' % go_fn)
    w('\treturn &DiagnosticRuleSet{')
    for ts_name, go_name, go_type, _ in fields:
        literal = values[ts_name]
        if go_type == "bool":
            assert literal in ("true", "false"), f"{ts_fn}.{ts_name} = {literal}"
            w('\t\t%s: %s,' % (go_name, literal))
        else:
            w('\t\t%s: %s,' % (go_name, '"%s"' % literal.strip("'")))
    w('\t}')
    w('}')

out_path.write_text("\n".join(o) + "\n")
print(
    "wrote %s: %d rules, %d fields, %d presets"
    % (out_path, len(rule_names), len(fields), len(presets))
)
