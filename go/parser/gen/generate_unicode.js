/*
 * generate_unicode.js
 *
 * One-shot code generator that transliterates
 * pyright-internal/src/parser/unicode.ts (v1.1.412) into Go.
 *
 * unicode.ts is itself generated (by build/generateUnicodeTables.py from
 * UnicodeData.txt for Unicode 16.0) and is ~3600 lines of pure table data. It
 * is evaluated here and re-emitted as Go so the tables are guaranteed to hold
 * exactly the same code points, rather than being retyped.
 *
 * Usage:
 *   node generate_unicode.js <path-to-src/parser/unicode.ts> <output.go>
 */

'use strict';

const fs = require('fs');
const vm = require('vm');

const inputPath = process.argv[2];
const outputPath = process.argv[3];

if (!inputPath || !outputPath) {
    console.error('usage: node generate_unicode.js <unicode.ts> <output.go>');
    process.exit(1);
}

const ts = fs.readFileSync(inputPath, 'utf8');

// Strip the TypeScript-only constructs so the remainder is valid JavaScript:
// the `export type` aliases, the `export` keyword, and the type annotations on
// each `const`.
const js = ts
    .replace(/^export type .*$/gm, '')
    .replace(/^export const (\w+): \w+ = /gm, 'const $1 = ');

const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(js + '\n;globalThis.__tables = { ' +
    [...ts.matchAll(/^export const (\w+):/gm)].map((m) => m[1]).join(', ') +
    ' };', sandbox);

const tables = sandbox.__tables;

const rangeTableNames = [];
const surrogateTableNames = [];
for (const [name, value] of Object.entries(tables)) {
    if (Array.isArray(value)) {
        rangeTableNames.push(name);
    } else {
        surrogateTableNames.push(name);
    }
}

function exported(name) {
    return name.charAt(0).toUpperCase() + name.slice(1);
}

function hex(n) {
    return '0x' + n.toString(16).padStart(4, '0');
}

// A UnicodeRange in TypeScript is either [start, end] or a bare code point.
// Both collapse to the same Go struct; a bare code point becomes start == end,
// which is exactly how characters.ts consumes it.
function emitRange(entry) {
    if (Array.isArray(entry)) {
        return `{${hex(entry[0])}, ${hex(entry[1])}}`;
    }
    return `{${hex(entry)}, ${hex(entry)}}`;
}

const out = [];
out.push('/*');
out.push(' * unicode_gen.go');
out.push(' * Copyright (c) Microsoft Corporation.');
out.push(' * Licensed under the MIT license.');
out.push(' *');
out.push(' * Tables that encode Unicode character codes for various Unicode-');
out.push(' * defined categories used in the Python spec.');
out.push(' *');
out.push(' * Generated by build/generateUnicodeTables.py from the UnicodeData.txt');
out.push(' * metadata file for Unicode 16.0, transliterated from parser/unicode.ts');
out.push(' * (pyright 1.1.412) by parser/gen/generate_unicode.js. DO NOT EDIT.');
out.push(' */');
out.push('');
out.push('package parser');
out.push('');
out.push('// UnicodeRange corresponds to the `[number, number] | number` union in');
out.push('// unicode.ts. A bare code point is stored as Start == End, which is how');
out.push('// characters.ts already treats it.');
out.push('type UnicodeRange struct {');
out.push('\tStart int');
out.push('\tEnd   int');
out.push('}');
out.push('');
out.push('// UnicodeRangeTable corresponds to the UnicodeRangeTable type.');
out.push('type UnicodeRangeTable []UnicodeRange');
out.push('');
out.push('// UnicodeSurrogateRangeTable corresponds to the UnicodeSurrogateRangeTable type.');
out.push('type UnicodeSurrogateRangeTable map[int]UnicodeRangeTable');
out.push('');

let totalRanges = 0;

for (const name of rangeTableNames) {
    const table = tables[name];
    totalRanges += table.length;
    out.push(`var ${exported(name)} = UnicodeRangeTable{`);
    for (const entry of table) {
        out.push(`\t${emitRange(entry)},`);
    }
    out.push('}');
    out.push('');
}

for (const name of surrogateTableNames) {
    const table = tables[name];
    out.push(`var ${exported(name)} = UnicodeSurrogateRangeTable{`);
    // Emit in ascending numeric key order. JavaScript object keys that look
    // like array indices already iterate in ascending numeric order, so this
    // preserves the source ordering; it also makes the output deterministic.
    const keys = Object.keys(table)
        .map(Number)
        .sort((a, b) => a - b);
    for (const key of keys) {
        totalRanges += table[key].length;
        out.push(`\t${hex(key)}: {`);
        for (const entry of table[key]) {
            out.push(`\t\t${emitRange(entry)},`);
        }
        out.push('\t},');
    }
    out.push('}');
    out.push('');
}

fs.writeFileSync(outputPath, out.join('\n'));
console.log(
    `generated ${outputPath}: ${rangeTableNames.length} range tables, ` +
        `${surrogateTableNames.length} surrogate tables, ${totalRanges} ranges`
);
